# управляющие символы и невидимые символы направления/нулевой ширины
_HIDDEN = re.compile("[\x00-\x08\x0b\x0c\x0e-\x1f\x7f​-‏‪-‮⁠-⁩﻿]")


def clean(s, limit=4000):
    if not s:
        return ""
    s = _HIDDEN.sub("", str(s))
    return s if len(s) <= limit else s[:limit] + "…"


def name(s):
    return clean(s, 120)
